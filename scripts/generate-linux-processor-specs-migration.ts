import {
  LINUX_PROCESSOR_SPEC_RULES,
  type ProcessorSpecRule,
} from "../lib/db/derivedtables/linux-processor-specs"

const quote = (value: string) => `'${value.replaceAll("'", "''")}'`
const condition = (rule: ProcessorSpecRule) =>
  `chip_family = ${quote(rule.family)} AND (${rule.parts.map((part) => `UPPER(TRIM(mfr)) GLOB ${quote(part)}`).join(" OR ")})`
const cases = (
  rules: readonly ProcessorSpecRule[],
  field: "cores" | "speedHz",
) =>
  `CASE\n${rules.map((rule) => `    WHEN ${condition(rule)} THEN ${rule[field]}`).join("\n")}\n    ELSE NULL END`

export const generateLinuxProcessorSpecsMigration =
  () => `-- Generated by bun scripts/generate-linux-processor-specs-migration.ts.
-- Evidence and field semantics: docs/generated/linux_capable_processors.md.
ALTER TABLE linux_capable_processor ADD COLUMN cpu_speed_hz REAL;
ALTER TABLE linux_capable_processor ADD COLUMN cpu_core_count INTEGER;

-- Split unit-bearing catalog CPU frequencies (including mixed MCU/MPU speeds).
-- Never interpret bare numbers, malformed JSON or placeholders as a frequency.
WITH RECURSIVE
raw AS (
  SELECT lcsc, json_extract(CASE WHEN json_valid(attributes) THEN attributes ELSE '{}' END,
    '$."CPU Maximum Speed"') AS speed FROM linux_capable_processor
),
split(lcsc, token, rest) AS (
  SELECT lcsc, '',
    replace(replace(replace(replace(replace(replace(lower(speed),
      ' ', ''), char(9), ''), char(10), ''), char(13), ''), ';', ','), '、', ',') || ','
  FROM raw WHERE typeof(speed) = 'text'
  UNION ALL
  SELECT lcsc, substr(rest, 1, instr(rest, ',') - 1), substr(rest, instr(rest, ',') + 1)
  FROM split WHERE rest <> ''
),
units AS (
  SELECT lcsc,
    CASE WHEN substr(token, -3) IN ('ghz', 'mhz', 'khz') THEN substr(token, 1, length(token) - 3)
      WHEN substr(token, -2) = 'hz' THEN substr(token, 1, length(token) - 2) END AS digits,
    CASE substr(token, -3) WHEN 'ghz' THEN 1000000000 WHEN 'mhz' THEN 1000000
      WHEN 'khz' THEN 1000 ELSE 1 END AS multiplier
  FROM split
),
speeds AS (
  SELECT lcsc, CAST(digits AS REAL) * multiplier AS hz FROM units
  WHERE digits <> '' AND digits NOT GLOB '*[^0-9.]*'
    AND substr(digits, 1, 1) GLOB '[0-9]' AND substr(digits, -1) GLOB '[0-9]'
    AND length(digits) - length(replace(digits, '.', '')) <= 1
)
UPDATE linux_capable_processor SET cpu_speed_hz = (
  SELECT MAX(hz) FROM speeds WHERE speeds.lcsc = linux_capable_processor.lcsc AND hz > 0 AND hz <= 10000000000
);

-- Reject known oscillator metadata; its CPU speed still needs grade-specific evidence.
UPDATE linux_capable_processor SET cpu_speed_hz = NULL
WHERE chip_family = 'Rockchip RK3506' AND cpu_speed_hz = 24000000;

UPDATE linux_capable_processor SET cpu_core_count = ${cases(LINUX_PROCESSOR_SPEC_RULES, "cores")};

UPDATE linux_capable_processor SET cpu_speed_hz = COALESCE(
  cpu_speed_hz,
  ${cases(
    LINUX_PROCESSOR_SPEC_RULES.filter((rule) => rule.speedHz !== undefined),
    "speedHz",
  )}
);
`

if (import.meta.main)
  await Bun.write(
    new URL(
      "../cf-proxy/migrations/0021_linux_processor_specs.sql",
      import.meta.url,
    ),
    generateLinuxProcessorSpecsMigration(),
  )
