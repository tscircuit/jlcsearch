import { LINUX_PROCESSOR_MEMORY_RULES } from "../lib/db/derivedtables/linux-processor-memory"

const quote = (value: string) => `'${value.replaceAll("'", "''")}'`
const cases = (field: "sram_size_bytes" | "integrated_dram_size_bytes") =>
  `CASE\n${LINUX_PROCESSOR_MEMORY_RULES.map(
    (rule) =>
      `  WHEN chip_family = ${quote(rule.family)} AND (${rule.parts.map((part) => `UPPER(TRIM(mfr)) GLOB ${quote(part)}`).join(" OR ")}) THEN ${rule[field] ?? "NULL"}`,
  ).join("\n")}\n  ELSE NULL END`

export const generateLinuxProcessorMemoryMigration =
  () => `-- Generated by bun scripts/generate-linux-processor-memory-migration.ts.
-- Verified capacities and semantics: docs/linux-processor-memory.md.
-- Deliberately ignore catalog RAM Size: it can be external capacity or cache.
ALTER TABLE linux_capable_processor ADD COLUMN sram_size_bytes INTEGER;
ALTER TABLE linux_capable_processor ADD COLUMN integrated_dram_size_bytes INTEGER;

UPDATE linux_capable_processor SET
  sram_size_bytes = ${cases("sram_size_bytes")},
  integrated_dram_size_bytes = ${cases("integrated_dram_size_bytes")};
`

if (import.meta.main)
  await Bun.write(
    new URL(
      "../cf-proxy/migrations/0022_linux_processor_memory.sql",
      import.meta.url,
    ),
    generateLinuxProcessorMemoryMigration(),
  )
